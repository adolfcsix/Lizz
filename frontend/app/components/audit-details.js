// Giữ đầy đủ giá trị trong nhật ký; chỉ chuyển cách trình bày sang nhãn nghiệp vụ.
export function auditDetails(value) {
  if (value === null || value === undefined) return "<span>—</span>";
  if (typeof value !== "object")
    return esc(
      typeof value === "boolean"
        ? value
          ? "Có"
          : "Không"
        : Object.hasOwn(values, value)
          ? values[value]
          : String(value),
    );
  const entries = Array.isArray(value)
    ? value.map((v, i) => ["Mục " + (i + 1), v])
    : Object.entries(value);
  if (!entries.length) return "<span>—</span>";
  return (
    '<dl class="audit-details">' +
    entries
      .map(
        ([key, item]) =>
          `<div><dt>${esc(Object.hasOwn(labels, key) ? labels[key] : key)}</dt><dd>${auditDetails(item)}</dd></div>`,
      )
      .join("") +
    "</dl>"
  );
}
